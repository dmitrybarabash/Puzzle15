namespace Puzzle15.Common.DomainModel;

// Чем закончилась попытка добавить результат партии в таблицу рекордов
public enum AddBestScoreResult
{
    // Результат добавлен в таблицу и сохранён в файл
    Added,

    // Результат не попадает в таблицу рекордов
    NotBestScore,

    // Игрок отказался вводить имя
    PlayerDeclined,

    // Файл рекордов не прочитался, поэтому неизвестно, попадает ли результат в таблицу
    LoadFailed,

    // Результат попал в таблицу, но файл рекордов не сохранился
    SaveFailed
}
